-- ผูกเครื่องมือที่ seed ไว้แล้ว (mig 123) เข้ากับชนิด ด้วยชื่อที่ตรงกัน (best-effort)
update tools t set type_id = tt.id
from tool_types tt
where t.type_id is null and t.name = tt.name;

-- ✅ ตรวจผล: ควรได้ประมาณ 68 ชนิด (51+19−2 ที่ซ้ำ)
select count(*) as tool_types,
       count(*) filter (where std_personal > 0) as in_personal_kit,
       count(*) filter (where std_vehicle  > 0) as in_vehicle_kit
from tool_types;
