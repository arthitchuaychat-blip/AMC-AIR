--   ชุดประจำตัว 19 รายการ → std_personal = 1 · ชุดประจำรถ 51 รายการ → std_vehicle = 1
--   ชื่อที่อยู่ทั้ง 2 ชุด (สว่านไร้สาย, ชุดหกเหลี่ยม) → รวมเป็นชนิดเดียว มีทั้งสอง flag
--   id = 'tt-'||md5(name) เพื่อให้ชื่อเดียวกันชน id กัน แล้ว merge flag ได้ · รันซ้ำได้
-- รันใน Supabase → SQL Editor หลังรัน 179 แล้ว

-- ชุดประจำตัวช่าง (19) → std_personal = 1
insert into tool_types (id, name, std_personal, std_vehicle)
select 'tt-' || md5(n), n, 1, 0
from unnest(array[
  'กล่องเครื่องมือ','สว่านไร้สาย','ตลับเมตร','มีดคัตเตอร์','ระดับน้ำสั้น',
  'ค้อนเล็ก','กรรไกรตัดโลหะ','คีมปอกสายไฟ','ไขควงวัดไฟ','ไขควงสั้น','ไขควงยาว',
  'ชุดหกเหลี่ยม','เลื่อยตัดฝ้า','ดินสอ','แว่นตากันฝุ่น','ไฟคาดหน้าผาก',
  'รองเท้า','หมวก','เสื้อสะท้อนแสง'
]) as n
on conflict (id) do update set std_personal = greatest(tool_types.std_personal, excluded.std_personal);

