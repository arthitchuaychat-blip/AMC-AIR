-- 178: ตั้งหมวดที่ชื่อสื่อถึง "อะไหล่/อุปกรณ์เสริม" เป็นกลุ่ม part อัตโนมัติ
-- เพื่อให้โผล่ในแท็บหลักใหม่ "อุปกรณ์เสริม/อะไหล่" ของคลังสินค้าทันที (ต้องรัน mig 176 ก่อน)
-- เฉพาะหมวดที่ยังไม่ได้ตั้ง (mat_group is null) — ปรับเองภายหลังได้ที่ ตั้งค่า → จัดกลุ่มหมวดวัสดุ
update categories set mat_group = 'part'
where mat_group is null
  and id not like 'sv-%'
  and (name_th like '%อะไหล่%' or name_th like '%อุปกรณ์เสริม%');
