-- 159: เครดิตเทอมของลูกค้า (รีวิว "กลาง" ข้อ 2)
--
-- ปัญหา: ช่อง "ครบกำหนดชำระ" บนใบส่งของ/ใบแจ้งหนี้เปิดมาว่างเปล่า ไม่มีค่าเริ่มต้นให้
-- ธุรการที่รีบออกใบจึงมักปล่อยว่าง ผลคือ
--   (1) ใบนั้นไม่ถูกนับใน KPI "เกินกำหนดชำระ" ในรายงานลูกหนี้ — ค้าง 3 เดือนก็ไม่มีใครเห็นว่าต้องตาม
--   (2) กระแสเงินสดใช้ due_date || issue_date เป็นวันคาดว่าจะรับ → ไม่มี due_date = วางเงินเข้าเร็วกว่าจริง
--       ทั้งเดือน แล้วเอาไปวางแผนจ่ายซัพ/เงินเดือนจากตัวเลขที่ไม่จริง
--
-- แก้: เก็บเครดิตเทอมไว้ที่ลูกค้า แล้วให้ใบแจ้งหนี้เติม due_date = วันที่บิล + เครดิตเทอม ให้อัตโนมัติ
-- 0 = รับเงินสด/ครบกำหนดวันออกบิล (ค่าเริ่มต้น ตรงกับที่ร้านทำอยู่)

alter table customers add column if not exists credit_days int not null default 0;

comment on column customers.credit_days is 'เครดิตเทอม (วัน) — ใบแจ้งหนี้ใช้ตั้งวันครบกำหนดชำระอัตโนมัติ · 0 = ครบกำหนดวันออกบิล';

