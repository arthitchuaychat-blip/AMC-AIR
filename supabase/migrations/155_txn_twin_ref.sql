-- 155: ผูก "ชุดเบิกเข้างานอัตโนมัติ" กับ "ชุดรับของ" ที่เป็นต้นเหตุ (แก้บั๊กสต๊อกหายตอนยกเลิกรับของ)
--
-- ปัญหาเดิม: ตอนรับของตามใบสั่งซื้อที่ผูกใบเสนอราคา ระบบสร้าง 2 ชุดคู่กัน (ซื้อเข้า + เบิกเข้างาน)
-- แล้วตราด้วย po_no เหมือนกัน · เวลายกเลิกรับของ 1 รอบ โค้ดลบด้วย `.eq("po_no", po_no)` เฉย ๆ
-- ⇒ ถ้าใบนั้นทยอยรับหลายรอบ รายการรับของ "รอบก่อนหน้า" ถูกลบไปด้วยทั้งหมด
-- สต๊อกหายทั้งที่ของกองอยู่ในคลังจริง และต้นทุนที่เบิกเข้างานของรอบก่อนก็หายตาม (กำไรงานพุ่งผิด)
--
-- วิธีแก้: ให้แถวเบิกอัตโนมัติจำ "เลขชุดรับของ" ที่เป็นต้นเหตุไว้ → ยกเลิกรอบไหนก็ลบเฉพาะคู่ของรอบนั้น
alter table transactions add column if not exists twin_ref text;
create index if not exists transactions_twin_ref_idx on transactions(twin_ref);

